import os
from datetime import datetime
from typing import Optional, List, Dict, Any
from sqlalchemy import (
    Integer,
    String,
    Text,
    DateTime,
    JSON,
    ForeignKey,
    func
)
from sqlalchemy.types import TypeDecorator
from sqlalchemy.orm import relationship, Mapped, mapped_column
from pgvector.sqlalchemy import Vector

from backend.db.base import Base, utcnow


class AdaptiveVector(TypeDecorator):
    """
    Adaptive vector embedding storage:
    Uses native pgvector Vector(384) when the environment or database has the 'vector' extension,
    and falls back to JSON format when running on native Windows PostgreSQL without pgvector or SQLite.
    """
    impl = JSON
    cache_ok = True

    def __init__(self, dim: int = 384, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self.dim = dim

    def load_dialect_impl(self, dialect):
        if dialect.name == "postgresql" and os.environ.get("ENABLE_PGVECTOR_TYPE", "").lower() in ("1", "true"):
            return dialect.type_descriptor(Vector(self.dim))
        return dialect.type_descriptor(JSON())


class KnowledgeDocument(Base):
    """Admin-uploaded clinical reference guideline entity (FR-04.1, FR-08.1)."""
    __tablename__ = "knowledge_documents"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    title: Mapped[str] = mapped_column(String(255), nullable=False)
    category: Mapped[Optional[str]] = mapped_column(String(100), default="Clinical Guideline", nullable=True)
    source_url: Mapped[Optional[str]] = mapped_column(String(500), nullable=True)
    uploaded_by: Mapped[Optional[int]] = mapped_column(
        Integer,
        ForeignKey("users.id", ondelete="SET NULL"),
        nullable=True
    )
    status: Mapped[str] = mapped_column(String(50), default="Reviewed", nullable=False)
    created_at: Mapped[datetime] = mapped_column(DateTime(timezone=True), default=utcnow, server_default=func.now())

    # Relationships
    uploader: Mapped[Optional["User"]] = relationship("User")
    chunks: Mapped[List["DocumentChunk"]] = relationship(
        "DocumentChunk",
        back_populates="document",
        cascade="all, delete-orphan",
        order_by="DocumentChunk.chunk_index"
    )

    def __repr__(self) -> str:
        return f"<KnowledgeDocument id={self.id} title='{self.title}'>"


class DocumentChunk(Base):
    """Recursive semantic text chunk with 384-dim dense vector embedding (FR-04.2 - FR-04.4)."""
    __tablename__ = "document_chunks"

    id: Mapped[int] = mapped_column(Integer, primary_key=True, autoincrement=True)
    document_id: Mapped[int] = mapped_column(
        Integer,
        ForeignKey("knowledge_documents.id", ondelete="CASCADE"),
        nullable=False,
        index=True
    )
    chunk_index: Mapped[int] = mapped_column(Integer, nullable=False)
    chunk_text: Mapped[str] = mapped_column(Text, nullable=False)
    # 384-dimensional dense vector embeddings generated by all-MiniLM-L6-v2
    embedding = mapped_column(AdaptiveVector(384), nullable=False)
    metadata_json: Mapped[Optional[Dict[str, Any]]] = mapped_column(JSON, nullable=True)

    # Relationship
    document: Mapped["KnowledgeDocument"] = relationship("KnowledgeDocument", back_populates="chunks")

    def __repr__(self) -> str:
        return f"<DocumentChunk id={self.id} doc_id={self.document_id} idx={self.chunk_index}>"
